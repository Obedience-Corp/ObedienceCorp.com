export type Cell = { x: number; y: number; w: number; h: number };

export function bitmapLine(text: string, scale: number, tracking = 1): {
  width: number;
  height: number;
  cells: Cell[];
} {
  const cells: Cell[] = [];
  let x = 0;
  const step = 7 + tracking;
  for (const raw of text.toUpperCase()) {
    const rows = CAP7[raw] ?? CAP7[" "];
    for (let y = 0; y < 7; y++) {
      const bits = rows[y];
      for (let col = 0; col < 7; col++) {
        if (bits & (0x40 >> col)) {
          cells.push({
            x: (x + col) * scale,
            y: y * scale,
            w: scale,
            h: scale,
          });
        }
      }
    }
    x += step;
  }
  return {
    width: Math.max(0, (x - tracking) * scale),
    height: 7 * scale,
    cells,
  };
}
